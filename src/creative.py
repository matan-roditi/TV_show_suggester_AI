import os
from typing import Literal

from dotenv import load_dotenv
from google import genai

# Load .env so GEMINI_API_KEY is available during runtime creative stage
ROOT_DIR = os.path.dirname(os.path.dirname(__file__))
load_dotenv(os.path.join(ROOT_DIR, ".env"))

_client = None


def _get_client() -> genai.Client:
    """Lazy initialization of the client to avoid import-time API key requirement."""
    global _client
    if _client is None:
        api_key = os.environ.get("GEMINI_API_KEY")
        if api_key:
            _client = genai.Client(api_key=api_key)
        else:
            # Falls back to ADC (Application Default Credentials) if configured
            _client = genai.Client()
    return _client


def generate_new_show_idea(
    source_shows: list[str],
    mode: Literal["input_based", "recommendation_based"],
) -> str:
    """
    Generate a creative TV show idea based on user input or recommendations.

    Returns a single text block (title + plot + themes), as generated by the model.
    """
    if not source_shows:
        raise ValueError("source_shows cannot be empty")

    if mode not in ("input_based", "recommendation_based"):
        raise ValueError("Invalid mode: must be 'input_based' or 'recommendation_based'")

    shows_str = ", ".join(source_shows)

    if mode == "input_based":
        prompt = (
            f"Based on these TV shows that the user loved: {shows_str}\n\n"
            "Generate a creative and original TV show idea that they might enjoy.\n"
            "Include:\n"
            "- A catchy title\n"
            "- A one-paragraph plot summary\n"
            "- The main themes it explores\n\n"
            "Be creative and original; don't copy existing shows."
        )
    else:
        prompt = (
            f"Based on these TV shows that were recommended to the user: {shows_str}\n\n"
            "Generate a creative and original TV show idea that complements these recommendations.\n"
            "Include:\n"
            "- A catchy title\n"
            "- A one-paragraph plot summary\n"
            "- The main themes it explores\n\n"
            "Be creative and original; don't copy existing shows."
        )

    client = _get_client()
    response = client.models.generate_content(model="gemini-1.5-flash", contents=prompt)

    text = getattr(response, "text", None)
    return text.strip() if text else "Description unavailable."
